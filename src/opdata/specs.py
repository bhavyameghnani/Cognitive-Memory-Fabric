"""Hand-authored client specifications (the 'controlled templates and explicit rules' of the generator).

Everything here is deterministic data. Anything that is NOT directly backed by a conversation turn is synthetic
and is labelled as such downstream. Evidence tuples are (interaction_id, turn_index, excerpt, kind) and are
verified against conversations.csv by the generator: an excerpt that is not in that turn aborts the build.

evidence kinds:
  explicit   the figure/fact is stated in that turn
  derived    the value is computed from explicit statements (documented in the note)
  decision   the turn records the decision/instruction that this record implements
               (execution date, amount split and instruments are synthetic unless the turn says otherwise)
  implied    the turn only implies the fact
  design_doc not conversation evidence: taken from docs/dataset_design.md (no interaction/turn)
"""
from __future__ import annotations

from datetime import date

D = date.fromisoformat

# ------------------------------------------------------------------ helpers for spec brevity
def A(key, atype, name, opened, investable=True, restriction="none", status="active", closed=None):
    return dict(key=key, type=atype, name=name, opened=D(opened), investable=investable,
                restriction=restriction, status=status, closed=D(closed) if closed else None)


def H(key, inst, acct, pct=None, usd=None, qty=None, bought="2020-01-01", ratio=None, note="", ev=None):
    """pct = share of the investable Jan-31 total (relative, normalised); usd/qty = fixed; none = opened by an event."""
    return dict(key=key, inst=inst, acct=acct, pct=pct, usd=usd, qty=qty, bought=D(bought), ratio=ratio, note=note, ev=ev or [])


def G(key, ver, gtype, desc, amount, tdate, prio, conf, status, vfrom, vto=None, aprov="synthetic", note="", ev=None):
    return dict(key=key, ver=ver, gtype=gtype, desc=desc, amount=amount, tdate=D(tdate) if tdate else None, prio=prio,
                conf=conf, status=status, vfrom=D(vfrom), vto=D(vto) if vto else None, aprov=aprov, note=note, ev=ev or [])


# evidence shorthand
def X(i, t, ex, kind="explicit", field=None, note=""):
    return dict(i=i, t=t, ex=ex, kind=kind, field=field, note=note)


DESIGN = lambda field, note: dict(i=None, t=None, ex=None, kind="design_doc", field=field, note=note)

